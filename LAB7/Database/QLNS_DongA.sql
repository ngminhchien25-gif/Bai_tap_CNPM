/* Bai 7 - Quan ly nhan su - cong ty son Dong A | SQL Server */
IF DB_ID(N'QLNS_DongA') IS NOT NULL DROP DATABASE QLNS_DongA;
GO
CREATE DATABASE QLNS_DongA COLLATE Vietnamese_CI_AS;
GO
USE QLNS_DongA;
GO
/* ===== DANH MUC ===== */
CREATE TABLE PhongBan(MaPB VARCHAR(10) PRIMARY KEY, TenPB NVARCHAR(100) NOT NULL, MoTa NVARCHAR(200) NULL, MaTruongPhong VARCHAR(10) NULL);
CREATE TABLE ChucVu(MaCV VARCHAR(10) PRIMARY KEY, TenCV NVARCHAR(100) NOT NULL, PhuCapMacDinh DECIMAL(18,0) NOT NULL DEFAULT 0);
CREATE TABLE CaLamViec(MaCa VARCHAR(10) PRIMARY KEY, TenCa NVARCHAR(50) NOT NULL, GioBatDau TIME NOT NULL, GioKetThuc TIME NOT NULL);
CREATE TABLE ThamSo(MaThamSo VARCHAR(30) PRIMARY KEY, GiaTri DECIMAL(18,4) NOT NULL);
/* ===== NHAN VIEN ===== */
CREATE TABLE NhanVien(
 MaNV VARCHAR(10) PRIMARY KEY, HoTen NVARCHAR(100) NOT NULL, NgaySinh DATE NULL, GioiTinh NVARCHAR(5) NULL,
 CCCD VARCHAR(12) NOT NULL UNIQUE, DiaChi NVARCHAR(200) NULL, SDT VARCHAR(15) NULL, Email VARCHAR(100) NULL,
 NgayVaoLam DATE NULL,
 TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Chờ tuyển dụng' CHECK (TrangThai IN (N'Chờ tuyển dụng',N'Thử việc',N'Chính thức',N'Nghỉ việc')),
 MaPB VARCHAR(10) NULL REFERENCES PhongBan(MaPB));
ALTER TABLE PhongBan ADD CONSTRAINT FK_PB_TruongPhong FOREIGN KEY(MaTruongPhong) REFERENCES NhanVien(MaNV);
/* ===== QUYET DINH (cha) + con 1-1 ===== */
CREATE TABLE QuyetDinh(
 SoQD VARCHAR(20) PRIMARY KEY, LoaiQD NVARCHAR(20) NOT NULL CHECK (LoaiQD IN (N'TuyenDung',N'ChucVu',N'Luong',N'KhenThuong',N'KyLuat')),
 NgayLap DATE NOT NULL DEFAULT GETDATE(), NgayHieuLuc DATE NOT NULL, NguoiKy NVARCHAR(100) NULL, NoiDung NVARCHAR(MAX) NULL,
 TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Nháp' CHECK (TrangThai IN (N'Nháp',N'Chờ duyệt',N'Đã ký',N'Từ chối',N'Huỷ')));
CREATE TABLE QDTuyenDung(
 SoQD VARCHAR(20) PRIMARY KEY REFERENCES QuyetDinh(SoQD), MaNV VARCHAR(10) NOT NULL REFERENCES NhanVien(MaNV),
 MaPB VARCHAR(10) NOT NULL REFERENCES PhongBan(MaPB), NgayBatDauTV DATE NOT NULL, NgayKetThucTV DATE NOT NULL,
 LuongThuViec DECIMAL(18,0) NOT NULL CHECK (LuongThuViec>0), DieuKhoanBenA NVARCHAR(MAX) NULL, DieuKhoanBenB NVARCHAR(MAX) NULL,
 CONSTRAINT CK_TV CHECK (NgayKetThucTV>NgayBatDauTV));
CREATE TABLE QDChucVu(SoQD VARCHAR(20) PRIMARY KEY REFERENCES QuyetDinh(SoQD), MaNV VARCHAR(10) NOT NULL REFERENCES NhanVien(MaNV),
 MaCV VARCHAR(10) NOT NULL REFERENCES ChucVu(MaCV), PhuCapChucVu DECIMAL(18,0) NOT NULL DEFAULT 0);
CREATE TABLE QDLuong(SoQD VARCHAR(20) PRIMARY KEY REFERENCES QuyetDinh(SoQD), MaNV VARCHAR(10) NOT NULL REFERENCES NhanVien(MaNV),
 LuongCoBan DECIMAL(18,0) NOT NULL CHECK (LuongCoBan>0), PhuCapLuong DECIMAL(18,0) NOT NULL DEFAULT 0, PhuCapDocHai DECIMAL(18,0) NOT NULL DEFAULT 0);
CREATE TABLE QDKhenThuong(SoQD VARCHAR(20) PRIMARY KEY REFERENCES QuyetDinh(SoQD),
 LoaiDoiTuong NVARCHAR(10) NOT NULL CHECK (LoaiDoiTuong IN (N'CaNhan',N'TapThe')),
 LoaiKhenThuong NVARCHAR(20) NOT NULL CHECK (LoaiKhenThuong IN (N'Thường',N'Lễ',N'Cuối năm',N'Lương tháng 13')),
 HinhThuc NVARCHAR(100) NULL, SoTien DECIMAL(18,0) NOT NULL CHECK (SoTien>0), LyDo NVARCHAR(300) NULL);
CREATE TABLE QDKyLuat(SoQD VARCHAR(20) PRIMARY KEY REFERENCES QuyetDinh(SoQD),
 LoaiDoiTuong NVARCHAR(10) NOT NULL CHECK (LoaiDoiTuong IN (N'CaNhan',N'TapThe')),
 HinhThuc NVARCHAR(100) NULL, SoTienPhat DECIMAL(18,0) NOT NULL DEFAULT 0, CachThu NVARCHAR(20) NOT NULL CHECK (CachThu IN (N'Nộp phạt',N'Trừ lương')), LyDo NVARCHAR(300) NULL);
CREATE TABLE ChiTietDoiTuongQD(Id INT IDENTITY PRIMARY KEY, SoQD VARCHAR(20) NOT NULL REFERENCES QuyetDinh(SoQD),
 MaNV VARCHAR(10) NULL REFERENCES NhanVien(MaNV), MaPB VARCHAR(10) NULL REFERENCES PhongBan(MaPB),
 CONSTRAINT CK_DoiTuong CHECK ((MaNV IS NULL AND MaPB IS NOT NULL) OR (MaNV IS NOT NULL AND MaPB IS NULL)));
/* ===== HOP DONG & BAO HIEM ===== */
CREATE TABLE HopDong(SoHD VARCHAR(20) PRIMARY KEY, MaNV VARCHAR(10) NOT NULL REFERENCES NhanVien(MaNV),
 SoQDTuyenDung VARCHAR(20) NOT NULL REFERENCES QDTuyenDung(SoQD), LoaiHD NVARCHAR(10) NOT NULL CHECK (LoaiHD IN (N'DaiHan',N'NganHan')),
 NgayBatDau DATE NOT NULL, NgayKetThuc DATE NULL, TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Hiệu lực',
 CONSTRAINT CK_HD CHECK (NgayKetThuc IS NULL OR NgayKetThuc>NgayBatDau));
CREATE TABLE HoSoBaoHiem(MaHSBH VARCHAR(20) PRIMARY KEY, SoHD VARCHAR(20) NOT NULL UNIQUE REFERENCES HopDong(SoHD),
 SoBHYT VARCHAR(20) NULL, SoBHXH VARCHAR(20) NULL, NgayThamGia DATE NOT NULL, MucDong DECIMAL(18,0) NOT NULL);
/* ===== PHAN CONG, CHAM CONG, PHU TROI ===== */
CREATE TABLE KeHoachTuan(MaKH VARCHAR(20) PRIMARY KEY, MaPB VARCHAR(10) NOT NULL REFERENCES PhongBan(MaPB), TuNgay DATE NOT NULL, DenNgay DATE NOT NULL,
 NguoiLap NVARCHAR(100) NULL, TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Nháp', CHECK (DenNgay>=TuNgay));
CREATE TABLE ChiTietPhanCong(MaKH VARCHAR(20) REFERENCES KeHoachTuan(MaKH), MaNV VARCHAR(10) REFERENCES NhanVien(MaNV), Ngay DATE,
 MaCa VARCHAR(10) NOT NULL REFERENCES CaLamViec(MaCa), CoPhuTroi BIT NOT NULL DEFAULT 0, PRIMARY KEY(MaKH,MaNV,Ngay));
CREATE TABLE BangChamCong(MaBCC VARCHAR(20) PRIMARY KEY, Thang INT NOT NULL CHECK (Thang BETWEEN 1 AND 12), Nam INT NOT NULL,
 MaPB VARCHAR(10) NOT NULL REFERENCES PhongBan(MaPB), NguoiLap NVARCHAR(100) NULL, DaChot BIT NOT NULL DEFAULT 0, UNIQUE(Thang,Nam,MaPB));
CREATE TABLE ChiTietChamCong(MaBCC VARCHAR(20) REFERENCES BangChamCong(MaBCC), MaNV VARCHAR(10) REFERENCES NhanVien(MaNV), Ngay DATE,
 MaCa VARCHAR(10) NULL REFERENCES CaLamViec(MaCa), TrangThai NVARCHAR(20) NOT NULL CHECK (TrangThai IN (N'Đi làm',N'Nghỉ phép',N'Vắng')),
 SoGioLam DECIMAL(4,1) NOT NULL DEFAULT 8, PRIMARY KEY(MaBCC,MaNV,Ngay));
CREATE TABLE PhieuPhuTroi(SoPhieu VARCHAR(20) PRIMARY KEY, NgayPhuTroi DATE NOT NULL,
 HinhThuc NVARCHAR(20) NOT NULL CHECK (HinhThuc IN (N'Tăng ca',N'Ngày lễ',N'Ngày nghỉ')), MaPB VARCHAR(10) NOT NULL REFERENCES PhongBan(MaPB), NguoiLap NVARCHAR(100) NULL);
CREATE TABLE ChiTietPhuTroi(SoPhieu VARCHAR(20) REFERENCES PhieuPhuTroi(SoPhieu), MaNV VARCHAR(10) REFERENCES NhanVien(MaNV),
 SoGioPhuTroi DECIMAL(4,1) NOT NULL CHECK (SoGioPhuTroi>0), PRIMARY KEY(SoPhieu,MaNV));
/* ===== LUONG, THU, CHI ===== */
CREATE TABLE BangLuong(MaBL VARCHAR(20) PRIMARY KEY, Thang INT NOT NULL CHECK (Thang BETWEEN 1 AND 12), Nam INT NOT NULL,
 NgayLap DATE NOT NULL DEFAULT GETDATE(), DaChot BIT NOT NULL DEFAULT 0, UNIQUE(Thang,Nam));
CREATE TABLE ChiTietBangLuong(MaBL VARCHAR(20) REFERENCES BangLuong(MaBL), MaNV VARCHAR(10) REFERENCES NhanVien(MaNV),
 LuongCoBan DECIMAL(18,0), TongPhuCap DECIMAL(18,0), NgayCong DECIMAL(4,1), TienPhuTroi DECIMAL(18,0), TienThuong DECIMAL(18,0),
 KhauTruBH DECIMAL(18,0), KhauTruPhat DECIMAL(18,0), ThucLinh DECIMAL(18,0), PRIMARY KEY(MaBL,MaNV));
CREATE TABLE PhieuChiKhenThuong(SoPhieuChi VARCHAR(20) PRIMARY KEY, SoQD VARCHAR(20) NOT NULL UNIQUE REFERENCES QDKhenThuong(SoQD),
 SoTien DECIMAL(18,0) NOT NULL, NgayChi DATE NOT NULL);
CREATE TABLE PhieuThuNopPhat(SoPhieuThu VARCHAR(20) PRIMARY KEY, SoQD VARCHAR(20) NOT NULL UNIQUE REFERENCES QDKyLuat(SoQD),
 SoTien DECIMAL(18,0) NOT NULL, NgayThu DATE NOT NULL, HinhThuc NVARCHAR(20) NOT NULL CHECK (HinhThuc IN (N'Nộp phạt',N'Trừ lương')));
GO
